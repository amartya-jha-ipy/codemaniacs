import os
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

def generate_forensic_pdf(case_id: str, filename: str, sha256: str, risk_score: int, classification: str, briefing: str, output_path: str = "reports/evidence_report.pdf"):
    os.makedirs("reports", exist_ok=True)
    
    doc = SimpleDocTemplate(
        output_path,
        pagesize=letter,
        rightMargin=40, leftMargin=40,
        topMargin=40, bottomMargin=40
    )
    
    styles = getSampleStyleSheet()
    
    # Custom forensic color palette
    primary_color = colors.HexColor("#0f172a") # Slate 900
    accent_red = colors.HexColor("#e11d48")    # Rose 600
    neutral_bg = colors.HexColor("#f8fafc")    # Slate 50
    
    # Custom styles
    title_style = ParagraphStyle(
        'ForensicTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=16,
        textColor=primary_color,
        spaceAfter=4
    )
    
    subtitle_style = ParagraphStyle(
        'ForensicSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica-Oblique',
        fontSize=9,
        textColor=colors.HexColor("#64748b"),
        spaceAfter=15
    )
    
    heading_style = ParagraphStyle(
        'ForensicHeading',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=11,
        textColor=primary_color,
        spaceBefore=10,
        spaceAfter=6
    )
    
    body_style = ParagraphStyle(
        'ForensicBody',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        textColor=colors.HexColor("#334155"),
        leading=14,
        spaceAfter=8
    )

    story = []

    # Header Banner (Bihar Police Cyber Cell Simulation)
    story.append(Paragraph("BIHAR POLICE CYBER COMMAND CENTER", ParagraphStyle('AgencyHeader', fontName='Helvetica-Bold', fontSize=10, textColor=accent_red, spaceAfter=2)))
    story.append(Paragraph("ANVESH v2.0 — Digital Forensics & Malware Analysis Division", title_style))
    story.append(Paragraph(f"Official Case Evidence Dossier | Case ID: {case_id}", subtitle_style))
    story.append(HRFlowable(width="100%", thickness=1.5, color=primary_color, spaceAfter=15))

    # Specimen Metadata Table
    story.append(Paragraph("1. SPECIMEN CHAIN OF CUSTODY & INTEGRITY", heading_style))
    
    data = [
        [Paragraph("<b>Parameter</b>", body_style), Paragraph("<b>Recorded Forensic Value</b>", body_style)],
        [Paragraph("Target Filename", body_style), Paragraph(filename, body_style)],
        [Paragraph("Cryptographic Hash (SHA-256)", body_style), Paragraph(f"<font name='Courier' size=8>{sha256}</font>", body_style)],
        [Paragraph("Threat Classification", body_style), Paragraph(f"<font color='#e11d48'><b>{classification}</b></font>", body_style)],
        [Paragraph("Composite Risk Score", body_style), Paragraph(f"<b>{risk_score} / 100</b> (High Threat Threshold)", body_style)]
    ]
    
    t = Table(data, colWidths=[150, 384])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), neutral_bg),
        ('ALIGN', (0,0), (-1,-1), 'LEFT'),
        ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
        ('BOTTOMPADDING', (0,0), (-1,-1), 6),
        ('TOPPADDING', (0,0), (-1,-1), 6),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor("#cbd5e1")),
    ]))
    story.append(t)
    story.append(Spacer(1, 15))

    # AI Executive Briefing Section
    story.append(Paragraph("2. AI-ASSISTED INVESTIGATIVE BRIEFING", heading_style))
    story.append(Paragraph(briefing, body_style))
    story.append(Spacer(1, 10))

    # Static & Behavioral Analysis Summary
    story.append(Paragraph("3. STATIC MANIFEST & PERMISSION FINDINGS", heading_style))
    story.append(Paragraph("• <b>READ_SMS & READ_CONTACTS:</b> Requested without legitimate functional justification for the application profile.", body_style))
    story.append(Paragraph("• <b>Dynamic Code Loading (DCL):</b> Detected memory reflection patterns targeting unverified external DEX segments.", body_style))
    story.append(Paragraph("• <b>Network IOCs:</b> Unencrypted outbound socket connection attempts mapped to known C2 IP (185.220.101.5).", body_style))
    story.append(Spacer(1, 20))

    # Legal Sign-off Footer
    story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#94a3b8"), spaceAfter=10))
    story.append(Paragraph("<b>LEGAL NOTICE:</b> This technical evidence report was automatically generated by ANVESH v2.0 under authorized cyber cell investigative protocols. All cryptographic hashes and telemetry logs are permanently recorded for judicial submission.", ParagraphStyle('FooterText', fontName='Helvetica-Oblique', fontSize=7, textColor=colors.HexColor("#64748b"))))

    doc.build(story)
    return output_path